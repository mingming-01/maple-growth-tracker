# 간단한 메모리 캐시
CACHE = {}
CHARACTER_CACHE_TTL = 300
HISTORY_CACHE_TTL = 1800
AI_RESPONSE_CACHE = {}
AI_RESPONSE_CACHE_TTL = 6 * 60 * 60
AI_RESPONSE_CACHE_MAX_ENTRIES = 100


def get_ai_response_cache(prompt):
    """같은 프롬프트의 성공한 AI 결과를 일정 시간 재사용한다."""
    cache_key = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
    item = AI_RESPONSE_CACHE.get(cache_key)
    if not item:
        return None

    now = time.time()
    if now - item["cached_at"] > AI_RESPONSE_CACHE_TTL:
        AI_RESPONSE_CACHE.pop(cache_key, None)
        return None

    item["used_at"] = now
    return item["analysis"]


def set_ai_response_cache(prompt, analysis):
    if not analysis:
        return

    now = time.time()
    cache_key = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
    AI_RESPONSE_CACHE[cache_key] = {
        "analysis": analysis,
        "cached_at": now,
        "used_at": now,
    }

    while len(AI_RESPONSE_CACHE) > AI_RESPONSE_CACHE_MAX_ENTRIES:
        oldest_key = min(
            AI_RESPONSE_CACHE,
            key=lambda key: AI_RESPONSE_CACHE[key]["used_at"],
        )
        AI_RESPONSE_CACHE.pop(oldest_key, None)


def get_cache(key):
    item = CACHE.get(key)
    if not item:
        return None
    if time.time() - item["time"] > item["ttl"]:
        del CACHE[key]
        return None
    return item["data"]


def set_cache(key, data, ttl):
    CACHE[key] = {
        "time": time.time(),
        "data": data,
        "ttl": ttl,
        "saved_at": datetime.now().astimezone().isoformat(timespec="seconds")
    }


def get_cache_timestamp(key):
    item = CACHE.get(key)
    return item.get("saved_at") if item else None


def save_api_snapshot(cache_key, data):
    saved_at = datetime.now().astimezone().isoformat(timespec="seconds")
    try:
        with sqlite3.connect(SNAPSHOT_DB_PATH, timeout=5) as connection:
            connection.execute(
                """
                INSERT INTO api_snapshots (cache_key, payload, saved_at)
                VALUES (?, ?, ?)
                ON CONFLICT(cache_key) DO UPDATE SET
                    payload = excluded.payload,
                    saved_at = excluded.saved_at
                """,
                (cache_key, json.dumps(data, ensure_ascii=False), saved_at)
            )
        return saved_at
    except sqlite3.Error:
        print("성장 데이터 스냅샷 저장에 실패했습니다.")
        return None


def load_api_snapshot(cache_key):
    try:
        with sqlite3.connect(SNAPSHOT_DB_PATH, timeout=5) as connection:
            row = connection.execute(
                "SELECT payload, saved_at FROM api_snapshots WHERE cache_key = ?",
                (cache_key,)
            ).fetchone()
        if not row:
            return None, None
        return json.loads(row[0]), row[1]
    except (sqlite3.Error, ValueError, TypeError):
        print("성장 데이터 스냅샷을 불러오지 못했습니다.")
        return None, None


def with_data_status(data, status, saved_at=None):
    result = dict(data)
    result["dataStatus"] = status
    result["dataAsOf"] = saved_at
    return result


def is_temporary_nexon_failure(response):
    if response is None:
        return True
    return response.status_code in (408, 425, 429) or response.status_code >= 500


def stale_snapshot_response(cache_key, error_message):
    snapshot, saved_at = load_api_snapshot(cache_key)
    if snapshot is not None:
        return jsonify(with_data_status(snapshot, "stale", saved_at)), 200
    return jsonify({"error": error_message}), 503


def request_nexon_api(endpoint, params, historical=False):
    """넥슨 API를 호출하며 과거 기록 수집 요청은 초당 호출 수를 제한한다."""
    global _last_history_api_request_at

    if historical:
        with HISTORY_API_REQUEST_LOCK:
            elapsed = time.monotonic() - _last_history_api_request_at
            if elapsed < HISTORY_API_MIN_INTERVAL:
                time.sleep(HISTORY_API_MIN_INTERVAL - elapsed)
            _last_history_api_request_at = time.monotonic()

    return requests.get(
        f"{BASE_URL}/{endpoint}",
        headers=HEADERS,
        params=params,
        timeout=NEXON_API_TIMEOUT
    )


