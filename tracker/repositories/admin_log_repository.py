"""관리자 운영 로그의 DB 연결과 영속화를 담당한다."""
import os
import sqlite3
import time
from datetime import datetime
from zoneinfo import ZoneInfo

import psycopg
from psycopg.rows import dict_row

from tracker.services.performance_metrics import increment_metric, observe_metric

KOREA_TIMEZONE = ZoneInfo("Asia/Seoul")


class AdminLogRepository:
    """SQLite/PostgreSQL 차이를 저장소 경계 안에 캡슐화한다."""

    def __init__(self, runtime_state):
        self.state = runtime_state

    def connect(self):
        backend = self.state.log_db_backend
        started_at = time.perf_counter()
        try:
            if backend == "postgres":
                return psycopg.connect(
                    self.state.growth_database_url,
                    connect_timeout=3,
                    sslmode="require",
                    prepare_threshold=None,
                    row_factory=dict_row,
                )

            connection = sqlite3.connect(self.state.log_db_path, timeout=5)
            connection.row_factory = sqlite3.Row
            return connection
        finally:
            increment_metric(
                "db.connection_attempts", backend=backend, store="admin_logs"
            )
            observe_metric(
                "db.connection_ms",
                (time.perf_counter() - started_at) * 1000,
                backend=backend,
                store="admin_logs",
            )

    def initialize(self):
        if self.state.log_db_backend == "postgres":
            try:
                connection = self.connect()
                try:
                    with connection:
                        connection.execute("""
                            CREATE TABLE IF NOT EXISTS action_logs (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                created_at TIMESTAMPTZ NOT NULL,
                                action TEXT NOT NULL,
                                character_name TEXT,
                                world_name TEXT,
                                comparison_name TEXT,
                                result TEXT NOT NULL,
                                path TEXT,
                                status_code INTEGER,
                                duration_ms INTEGER,
                                error_type TEXT
                            )
                        """)
                        for column, definition in (
                            ("path", "TEXT"),
                            ("status_code", "INTEGER"),
                            ("duration_ms", "INTEGER"),
                            ("error_type", "TEXT"),
                        ):
                            connection.execute(
                                f"ALTER TABLE action_logs ADD COLUMN IF NOT EXISTS {column} {definition}"
                            )
                        connection.execute(
                            "CREATE INDEX IF NOT EXISTS idx_action_logs_created_at "
                            "ON action_logs (created_at DESC)"
                        )
                        connection.execute(
                            "ALTER TABLE action_logs ENABLE ROW LEVEL SECURITY"
                        )
                        connection.execute(
                            "REVOKE ALL ON TABLE action_logs FROM PUBLIC, anon, authenticated"
                        )
                finally:
                    connection.close()
                return
            except psycopg.Error:
                # 로그 저장소 장애가 앱 전체의 시작을 막지 않도록 로컬 저장소로 전환한다.
                print("영구 관리자 로그 저장소 초기화에 실패했습니다.")
                self.state.log_db_backend = "sqlite"
                self.state.log_storage_warning = (
                    "Supabase 로그 저장소에 연결하지 못해 임시 SQLite를 사용 중입니다. "
                    "이 환경의 로그는 재배포 후 유지되지 않을 수 있습니다."
                )

        os.makedirs(os.path.dirname(self.state.log_db_path), exist_ok=True)
        connection = sqlite3.connect(self.state.log_db_path, timeout=5)
        try:
            with connection:
                connection.execute("""
                    CREATE TABLE IF NOT EXISTS action_logs (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        created_at TEXT NOT NULL,
                        action TEXT NOT NULL,
                        character_name TEXT,
                        world_name TEXT,
                        comparison_name TEXT,
                        result TEXT NOT NULL,
                        path TEXT,
                        status_code INTEGER,
                        duration_ms INTEGER,
                        error_type TEXT
                    )
                """)
                existing_columns = {
                    row[1] for row in connection.execute(
                        "PRAGMA table_info(action_logs)"
                    )
                }
                for column, definition in (
                    ("path", "TEXT"),
                    ("status_code", "INTEGER"),
                    ("duration_ms", "INTEGER"),
                    ("error_type", "TEXT"),
                ):
                    if column not in existing_columns:
                        connection.execute(
                            f"ALTER TABLE action_logs ADD COLUMN {column} {definition}"
                        )
                connection.execute(
                    "CREATE INDEX IF NOT EXISTS idx_action_logs_created_at "
                    "ON action_logs (created_at DESC)"
                )
        finally:
            connection.close()

    def insert(self, *, action, character_name=None, world_name=None,
               result="성공", comparison_name=None, path=None, status_code=None,
               duration_ms=None, error_type=None):
        placeholder = "%s" if self.state.log_db_backend == "postgres" else "?"
        placeholders = ", ".join([placeholder] * 10)
        query = f"""
            INSERT INTO action_logs
                (created_at, action, character_name, world_name, comparison_name, result,
                 path, status_code, duration_ms, error_type)
            VALUES ({placeholders})
        """
        connection = self.connect()
        try:
            with connection:
                connection.execute(
                    query,
                    (
                        datetime.now(KOREA_TIMEZONE).isoformat(timespec="seconds"),
                        action,
                        character_name,
                        world_name,
                        comparison_name,
                        result,
                        path,
                        status_code,
                        duration_ms,
                        error_type,
                    ),
                )
        finally:
            connection.close()

    @staticmethod
    def _measure_query(query_name, operation, backend):
        started_at = time.perf_counter()
        try:
            return operation()
        finally:
            labels = {"backend": backend, "store": "admin_logs", "query": query_name}
            increment_metric("db.query_executions", **labels)
            observe_metric(
                "db.query_ms", (time.perf_counter() - started_at) * 1000, **labels
            )

    def search(self, search_text="", selected_action="", selected_result="",
               date_from=None, date_to=None):
        """검색 조건에 맞는 로그와 필터 선택지를 조회한다."""
        from datetime import datetime, timedelta

        placeholder = "%s" if self.state.log_db_backend == "postgres" else "?"
        conditions = []
        parameters = []

        if search_text:
            pattern = f"%{search_text}%"
            conditions.append(
                "("
                "COALESCE(action, '') LIKE " + placeholder
                + " OR COALESCE(path, '') LIKE " + placeholder
                + " OR COALESCE(character_name, '') LIKE " + placeholder
                + " OR COALESCE(world_name, '') LIKE " + placeholder
                + " OR COALESCE(comparison_name, '') LIKE " + placeholder
                + " OR COALESCE(error_type, '') LIKE " + placeholder
                + " OR COALESCE(CAST(status_code AS TEXT), '') LIKE " + placeholder
                + ")"
            )
            parameters.extend([pattern] * 7)

        if selected_action:
            conditions.append(f"action = {placeholder}")
            parameters.append(selected_action)
        if selected_result in ("성공", "실패"):
            conditions.append(f"result = {placeholder}")
            parameters.append(selected_result)

        def date_bound(day):
            value = datetime.combine(day, datetime.min.time()).replace(
                tzinfo=KOREA_TIMEZONE
            )
            return (
                value
                if self.state.log_db_backend == "postgres"
                else value.isoformat(timespec="seconds")
            )

        if date_from:
            conditions.append(f"created_at >= {placeholder}")
            parameters.append(date_bound(date_from))
        if date_to:
            conditions.append(f"created_at < {placeholder}")
            parameters.append(date_bound(date_to + timedelta(days=1)))

        where_clause = " WHERE " + " AND ".join(conditions) if conditions else ""
        rows = []
        total_count = 0
        action_options = []
        query_started = time.perf_counter()
        query_count = 0
        try:
            connection = self.connect()
            try:
                with connection:
                    count_row = self._measure_query(
                        "count",
                        lambda: connection.execute(
                            f"SELECT COUNT(*) AS total FROM action_logs{where_clause}",
                            parameters,
                        ).fetchone(),
                        self.state.log_db_backend,
                    )
                    query_count += 1
                    total_count = count_row["total"]

                    rows = self._measure_query(
                        "page",
                        lambda: connection.execute(
                            "SELECT created_at, action, character_name, world_name, comparison_name, "
                            "result, path, status_code, duration_ms, error_type "
                            f"FROM action_logs{where_clause} "
                            "ORDER BY created_at DESC, id DESC LIMIT 500",
                            parameters,
                        ).fetchall(),
                        self.state.log_db_backend,
                    )
                    query_count += 1
                    action_rows = self._measure_query(
                        "actions",
                        lambda: connection.execute(
                            "SELECT DISTINCT action FROM action_logs ORDER BY action"
                        ).fetchall(),
                        self.state.log_db_backend,
                    )
                    action_options = [row["action"] for row in action_rows]
                    query_count += 1
            finally:
                connection.close()
        finally:
            increment_metric("db.operations", operation="admin_logs.select")
            increment_metric(
                "db.sql_statements", query_count, operation="admin_logs.select"
            )
            observe_metric(
                "db.operation_ms",
                (time.perf_counter() - query_started) * 1000,
                operation="admin_logs.select",
            )

        return {
            "rows": rows,
            "total_count": total_count,
            "action_options": action_options,
        }

