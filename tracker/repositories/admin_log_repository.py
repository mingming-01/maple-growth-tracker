"""관리자 운영 로그의 DB 연결과 영속화를 담당한다."""
import os
import sqlite3
import time
from datetime import datetime
from zoneinfo import ZoneInfo

import psycopg
from psycopg.rows import dict_row

from tracker.services.performance_metrics import increment_metric, observe_metric

KOREA_TIMEZONE = ZoneInfo("Asia/Seoul")


class AdminLogRepository:
    """SQLite/PostgreSQL 차이를 저장소 경계 안에 캡슐화한다."""

    def __init__(self, runtime_state):
        self.state = runtime_state

    def connect(self):
        backend = self.state.log_db_backend
        started_at = time.perf_counter()
        try:
            if backend == "postgres":
                return psycopg.connect(
                    self.state.growth_database_url,
                    connect_timeout=3,
                    sslmode="require",
                    prepare_threshold=None,
                    row_factory=dict_row,
                )

            connection = sqlite3.connect(self.state.log_db_path, timeout=5)
            connection.row_factory = sqlite3.Row
            return connection
        finally:
            increment_metric(
                "db.connection_attempts", backend=backend, store="admin_logs"
            )
            observe_metric(
                "db.connection_ms",
                (time.perf_counter() - started_at) * 1000,
                backend=backend,
                store="admin_logs",
            )

    def initialize(self):
        if self.state.log_db_backend == "postgres":
            try:
                connection = self.connect()
                try:
                    with connection:
                        connection.execute("""
                            CREATE TABLE IF NOT EXISTS action_logs (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                created_at TIMESTAMPTZ NOT NULL,
                                action TEXT NOT NULL,
                                character_name TEXT,
                                world_name TEXT,
                                comparison_name TEXT,
                                result TEXT NOT NULL,
                                path TEXT,
                                status_code INTEGER,
                                duration_ms INTEGER,
                                error_type TEXT
                            )
                        """)
                        for column, definition in (
                            ("path", "TEXT"),
                            ("status_code", "INTEGER"),
                            ("duration_ms", "INTEGER"),
                            ("error_type", "TEXT"),
                        ):
                            connection.execute(
                                f"ALTER TABLE action_logs ADD COLUMN IF NOT EXISTS {column} {definition}"
                            )
                        connection.execute(
                            "CREATE INDEX IF NOT EXISTS idx_action_logs_created_at "
                            "ON action_logs (created_at DESC)"
                        )
                        connection.execute(
                            "ALTER TABLE action_logs ENABLE ROW LEVEL SECURITY"
                        )
                        connection.execute(
                            "REVOKE ALL ON TABLE action_logs FROM PUBLIC, anon, authenticated"
                        )
                finally:
                    connection.close()
                return
            except psycopg.Error:
                # 로그 저장소 장애가 앱 전체의 시작을 막지 않도록 로컬 저장소로 전환한다.
                print("영구 관리자 로그 저장소 초기화에 실패했습니다.")
                self.state.log_db_backend = "sqlite"
                self.state.log_storage_warning = (
                    "Supabase 로그 저장소에 연결하지 못해 임시 SQLite를 사용 중입니다. "
                    "이 환경의 로그는 재배포 후 유지되지 않을 수 있습니다."
                )

        os.makedirs(os.path.dirname(self.state.log_db_path), exist_ok=True)
        connection = sqlite3.connect(self.state.log_db_path, timeout=5)
        try:
            with connection:
                connection.execute("""
                    CREATE TABLE IF NOT EXISTS action_logs (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        created_at TEXT NOT NULL,
                        action TEXT NOT NULL,
                        character_name TEXT,
                        world_name TEXT,
                        comparison_name TEXT,
                        result TEXT NOT NULL,
                        path TEXT,
                        status_code INTEGER,
                        duration_ms INTEGER,
                        error_type TEXT
                    )
                """)
                existing_columns = {
                    row[1] for row in connection.execute(
                        "PRAGMA table_info(action_logs)"
                    )
                }
                for column, definition in (
                    ("path", "TEXT"),
                    ("status_code", "INTEGER"),
                    ("duration_ms", "INTEGER"),
                    ("error_type", "TEXT"),
                ):
                    if column not in existing_columns:
                        connection.execute(
                            f"ALTER TABLE action_logs ADD COLUMN {column} {definition}"
                        )
                connection.execute(
                    "CREATE INDEX IF NOT EXISTS idx_action_logs_created_at "
                    "ON action_logs (created_at DESC)"
                )
        finally:
            connection.close()

    def insert(self, *, action, character_name=None, world_name=None,
               result="성공", comparison_name=None, path=None, status_code=None,
               duration_ms=None, error_type=None):
        placeholder = "%s" if self.state.log_db_backend == "postgres" else "?"
        placeholders = ", ".join([placeholder] * 10)
        query = f"""
            INSERT INTO action_logs
                (created_at, action, character_name, world_name, comparison_name, result,
                 path, status_code, duration_ms, error_type)
            VALUES ({placeholders})
        """
        connection = self.connect()
        try:
            with connection:
                connection.execute(
                    query,
                    (
                        datetime.now(KOREA_TIMEZONE).isoformat(timespec="seconds"),
                        action,
                        character_name,
                        world_name,
                        comparison_name,
                        result,
                        path,
                        status_code,
                        duration_ms,
                        error_type,
                    ),
                )
        finally:
            connection.close()
